// QUESTION 2 — STRING CONCATENATION
// ------------------------------------------------------------ 
/* Create: firstName = "Mariam" lastName = "Rajput" Join them together and print: Mariam Rajput */
// ANSWER: 

let firstName = "Mariam"; 
let lastName = "Rajput"; 
let fullName = firstName + " " + lastName; 
console.log(fullName); 

